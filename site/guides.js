/** The guides the site actually publishes — a guide with no pack behind it is not a page. */
export function guidePages({ site = SITE, published = PUBLISHED } = {}) {
  const slugs = new Set(published.map((entry) => entry.slug));
  const pages = GUIDES.filter((entry) => slugs.has(entry.slug));
  if (!pages.length) return Object.freeze([]);
  return Object.freeze([
    Object.freeze({
      ...GUIDE_INDEX,
      links: Object.freeze(pages.map((entry) => Object.freeze({ path: entry.path, label: entry.title })))
    }),
    ...pages.map((entry) => Object.freeze({
      slug: `guide/${entry.slug}`,
      path: entry.path,
      title: entry.title,
      description: entry.description,
      sections: entry.sections,
      links: Object.freeze([
        Object.freeze({ path: entry.packPath, label: guideBackLabel(entry, published) }),
        Object.freeze({ path: GUIDE_INDEX.path, label: GUIDE_INDEX.title })
      ])
    }))
  ]);
}

/** «결혼 100제 풀어보기» — the pack's own name, so the link says where it goes. */
function guideBackLabel(entry, published) {
  const pack = published.find((each) => each.slug === entry.slug);
  return `${pack?.navTitle || pack?.title || entry.title} 풀어보기`;
}

/** The guide a pack's page links to, or null while that pack has none. */
export function guideFor(slug, { site = SITE, published = PUBLISHED } = {}) {
  return guidePages({ site, published }).find((page) => page.path === `/guide/${slug}/`) || null;
}
