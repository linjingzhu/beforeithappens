/**
 * 읽을거리 — one article per published pack.
 *
 * Why these exist at all. The site was fifty pages of questions and five of prose, and a reader who
 * opened three pages at random met three lists. Lists are what the site is for, but a list does not
 * say why the questions are in that order, what a reader is supposed to do with a disagreement, or
 * what the pack deliberately refuses to do. Those are the parts a person has to write, and they
 * were being carried in commit messages and in this repository's own documentation instead of on
 * the site where the reader is.
 *
 * What is in them, and what is not. Every claim here is about this site's own packs — how they are
 * built, what the ten parts are, how to use them, what they will not do. Nothing here cites
 * research, quotes a study or reports a statistic, because none was gathered for the four lifecycle
 * packs: 임신 100제 and 우울 100제 carry source lists in their editorial builds and the other four do
 * not, and an article that borrowed the authority of a citation it did not earn would be worse than
 * an article with none. Where a guide says something is common or difficult, it is describing what
 * the questions were written to meet, not reporting a finding.
 *
 * Each guide links to its pack and each pack's first page links back, so neither is an orphan.
 */

const guide = (slug, title, description, sections) => Object.freeze({
  slug,
  path: `/guide/${slug}/`,
  packPath: `/${slug}/`,
  title,
  description,
  sections: Object.freeze(sections.map((section) => Object.freeze({
    heading: section.heading,
    paragraphs: Object.freeze(section.paragraphs)
  })))
});

